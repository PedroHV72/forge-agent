#!/usr/bin/env node
'use strict';

/**
 * forge-workspace — what counts as a Forge project, and who owns a directory.
 *
 * Born from a measurement: of 18 registered projects on the author's machine,
 * 5 were not projects at all. `.gsd/` had been *manufactured* in them by our
 * own tooling — `forge-verify.js` ran `mkdirSync(cwd/.gsd/forge)` in every repo
 * it verified, and `forge-lock.js` ran `mkdirSync(cwd/.gsd/.locks)` wherever it
 * was invoked. Both wrote the exact marker the app uses to detect a project, so
 * touching a repo enrolled it. `~/Development/.gsd` was created that way too —
 * one directory above every real project, which is the containment hazard
 * `ProjectGrouping.swift` warns about.
 *
 * The fix is a predicate with a spine: presence of `.gsd/` proves a tool ran
 * here, not that work lives here. Only *work artifacts* prove that.
 *
 * Three states, because two would lie:
 *
 *   project — `.gsd/` holds at least one work artifact (milestones/, tasks/,
 *             items/, a ledger, memory, a hand-written STATE.md, …).
 *   touched — `.gsd/` exists but holds only runtime scratch (forge/, .locks/,
 *             a dashboard-generated STATE.md) or nothing. A repo some *other*
 *             project reached into. Real, worth showing, not a project.
 *   none    — no `.gsd/` at all.
 *
 * `touched` is deliberately not "hidden". A misclassification must cost a
 * click, never a project: callers are expected to surface touched directories
 * with an action to register them, the same way silence about an inert route
 * was the defect TASK-021 fixed. Hiding is indistinguishable from a broken
 * detector.
 *
 * Zero dependencies, no side effects — nothing in this file creates `.gsd/`.
 * That is the point of the file.
 *
 * The Swift mirror is `app/Sources/ForgeKit/ProjectMarker.swift`; the two are
 * kept in sync by `scripts/forge-app-workspace-marker.test.js`.
 */

const fs = require('fs');
const path = require('path');

/**
 * Entries inside `.gsd/` that prove a human (or a run acting for one) did work
 * here. Directories count even when empty: `/forge-init` scaffolds them, and
 * having been initialised is itself the claim we are testing for.
 */
const WORK_ENTRIES = [
  // Fragment stores and their legacy single-file forms.
  'milestones', 'tasks', 'items', 'ledger', 'LEDGER.md',
  'decisions', 'DECISIONS.md', 'memory', 'AUTO-MEMORY.md',
  'checker-memory', 'CHECKER-MEMORY.md',
  // Project-level statements of intent and standards.
  'PROJECT.md', 'REQUIREMENTS.md', 'CODING-STANDARDS.md', 'KNOWLEDGE.md',
  // Written by /forge-init; the cleanest "initialised here" signal there is.
  'SCHEMA-VERSION',
  // Operator-authored configuration.
  //
  // The legacy prefs filenames are deliberately absent: `forge-prefs.js` is the
  // sole production holder of those literals (dual-read boundary, guarded by
  // forge-smoke.js Section 39), and as evidence they are redundant anyway — a
  // project old enough to carry them also carries milestones and decisions.
  'forge-prefs.jsonc',
];

/**
 * Entries any running tool creates on its own. Never evidence.
 *
 * `STATE.md` is absent on purpose — it is conditional evidence, see
 * `stateIsGenerated`.
 */
const RUNTIME_ENTRIES = ['forge', '.locks'];

/** Header `forge-dashboard.js` stamps on every file it writes. */
const DASHBOARD_MARKER = 'AUTO-GENERATED by scripts/forge-dashboard.js';

/**
 * A dashboard-rendered STATE.md is runtime output, not work: regenerating the
 * dashboard from a directory is exactly how the phantom markers appeared. A
 * hand-written STATE.md, by contrast, is the orchestrator's record of a real
 * run and does count.
 *
 * Read failures resolve to "generated" (i.e. not evidence). An unreadable file
 * cannot support a claim.
 */
function stateIsGenerated(statePath) {
  try {
    const fd = fs.openSync(statePath, 'r');
    try {
      const buf = Buffer.alloc(200);
      const n = fs.readSync(fd, buf, 0, 200, 0);
      return buf.slice(0, n).toString('utf8').includes(DASHBOARD_MARKER);
    } finally {
      fs.closeSync(fd);
    }
  } catch {
    return true;
  }
}

/**
 * Classify a single directory. Pure: reads, never writes.
 *
 * Returns `{ kind, signals, entries }` where `signals` lists the work artifacts
 * that carried the decision — callers show it so a classification can be argued
 * with instead of merely obeyed.
 */
function classify(dir) {
  const gsd = path.join(dir, '.gsd');
  let entries;
  try {
    entries = fs.readdirSync(gsd);
  } catch {
    return { kind: 'none', signals: [], entries: [] };
  }

  const present = new Set(entries);
  const signals = WORK_ENTRIES.filter(e => present.has(e));

  if (present.has('STATE.md') && !stateIsGenerated(path.join(gsd, 'STATE.md'))) {
    signals.push('STATE.md');
  }

  return {
    kind: signals.length > 0 ? 'project' : 'touched',
    signals,
    entries,
  };
}

function isProject(dir) {
  return classify(dir).kind === 'project';
}

/**
 * The nearest directory at or above `startDir` that is a real project.
 *
 * This is the addressing rule for anything that wants to record something
 * about a directory: state belongs to the project that owns the work, not to
 * whatever repo a command happened to run in. A monorepo member with its own
 * `.gsd/` owns itself; a plain repo reached into by a run resolves upward to
 * the workspace that reached.
 *
 * Returns null when no ancestor qualifies — callers must treat that as "do not
 * record", never as "create one here".
 *
 * `stopAt` bounds the walk (tests, and to avoid wandering above $HOME).
 */
function resolveOwner(startDir, opts) {
  opts = opts || {};
  const stopAt = opts.stopAt ? path.resolve(opts.stopAt) : null;

  let dir = path.resolve(startDir);
  for (;;) {
    if (isProject(dir)) return dir;
    if (stopAt && dir === stopAt) return null;
    const parent = path.dirname(dir);
    if (parent === dir) return null; // filesystem root
    dir = parent;
  }
}

module.exports = {
  WORK_ENTRIES,
  RUNTIME_ENTRIES,
  DASHBOARD_MARKER,
  classify,
  isProject,
  resolveOwner,
};

// ── CLI ─────────────────────────────────────────────────────────────────────
if (require.main === module) {
  const argv = process.argv.slice(2);
  const json = argv.includes('--json');
  const positional = argv.filter(a => !a.startsWith('--'));
  const ownerFlag = argv.includes('--owner');
  const target = positional[0] || process.cwd();

  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write(
      'forge-workspace — classify a directory, or resolve the project that owns it\n\n' +
      'Usage:\n' +
      '  forge-workspace [dir] [--json]        classify dir (project|touched|none)\n' +
      '  forge-workspace [dir] --owner [--json]  print the owning project, if any\n');
    process.exit(0);
  }

  if (ownerFlag) {
    const owner = resolveOwner(target);
    if (json) {
      process.stdout.write(JSON.stringify({ dir: target, owner }) + '\n');
    } else if (owner) {
      process.stdout.write(owner + '\n');
    }
    process.exit(owner ? 0 : 1);
  }

  const r = classify(target);
  if (json) {
    process.stdout.write(JSON.stringify({ dir: target, ...r }) + '\n');
  } else {
    process.stdout.write(`${r.kind}\t${target}${r.signals.length ? '\t' + r.signals.join(',') : ''}\n`);
  }
  process.exit(r.kind === 'project' ? 0 : 1);
}
